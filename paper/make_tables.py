#!/usr/bin/env python3
"""Generate sim_tables.tex (LaTeX tables of the MuJoCo study) from the committed result files.

    python3 paper/make_tables.py

Reads experiments/bilateral_sim/results/{multi_seed,torque/studies}.json, so the numbers in the paper are copied
by a program, not by hand. Re-run after re-running the experiments.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "..", "experiments", "bilateral_sim", "results")
ms = json.load(open(os.path.join(RES, "multi_seed.json")))
S, PJ = ms["summary"], ms["per_joint"]

ROWS = [("Original code (re-implemented)", "Original code$^\\dagger$"), ("Unilateral position", "Unilateral"),
        ("Position-position", "Position--position"), ("Position-force", "Position--force"),
        ("Proposed, no MPC", "Proposed, no MPC"), ("Proposed", "\\textbf{Proposed}")]


def pm(m, f):
    return (f + "$\\pm$" + f).format(m["mean"], m["std"])


out = []
out.append("% generated by paper/make_tables.py -- do not edit by hand")
out.append("\\begin{table}[t]\n\\centering\n\\caption{Simulation (MuJoCo), "
           f"{ms['seeds']} seeds, mean$\\pm$std. Each seed redraws sensor noise and the operator trajectory. "
           "RMSE is pooled over the five joints. Lag is resolved at the 20\\,ms control period. "
           "Force corr.: Pearson correlation of the force felt at the master and the true wall force.}")
out.append("\\label{tab:sim_multiseed}\n\\resizebox{\\columnwidth}{!}{%\n\\begin{tabular}{lcccc}\n\\hline")
out.append("\\textbf{Controller} & \\textbf{RMSE free (rad)} & \\textbf{RMSE all (rad)} & \\textbf{Lag (ms)} & \\textbf{Force corr.} \\\\\n\\hline")
for key, lbl in ROWS:
    s = S[key]
    out.append(f"{lbl} & {pm(s['rmse_free'], '{:.3f}')} & {pm(s['rmse_all'], '{:.3f}')} & "
               f"{pm(s['lag_ms'], '{:.0f}')} & {pm(s['force_corr'], '{:.2f}')} \\\\")
out.append("\\hline\n\\end{tabular}%\n}\n\\end{table}")

joints = [("waist", "Waist"), ("shoulder", "Shoulder"), ("elbow", "Elbow"), ("wrist_angle", "Wrist Angle"),
          ("wrist_rotate", "Wrist Rotate")]
out.append("\n\\begin{table}[t]\n\\centering\n\\caption{Simulation counterpart of Table~\\ref{tab:tracking_metrics}: "
           f"per-joint tracking error over the whole task, mean of {ms['seeds']} seeds. Not comparable in magnitude "
           "with the hardware table (different operator, plant and controller).}")
out.append("\\label{tab:sim_joints}\n\\resizebox{\\columnwidth}{!}{%\n\\begin{tabular}{lcccccc}\n\\hline")
out.append("& \\multicolumn{3}{c}{\\textbf{Original code}$^\\dagger$} & \\multicolumn{3}{c}{\\textbf{Proposed}} \\\\")
out.append("\\textbf{Joint} & RMSE & MAE & Max & RMSE & MAE & Max \\\\\n\\hline")
for k, lbl in joints:
    a, b = PJ["Original code (re-implemented)"][k], PJ["Proposed"][k]
    out.append(f"{lbl} & {a['rmse']:.4f} & {a['mae']:.4f} & {a['max']:.4f} & {b['rmse']:.4f} & {b['mae']:.4f} & {b['max']:.4f} \\\\")
out.append("\\hline\n\\end{tabular}%\n}\n\\end{table}")

# torque mimicking (S2): the rows are read from studies.md, which torque_studies.py writes
rows = {}
for line in open(os.path.join(RES, "torque", "studies.md")):
    if line.startswith("| ") and line.count("|") == 8:
        c = [x.strip() for x in line.strip("|\n").split("|")]
        rows[c[0]] = c[1:]
sel = [("Original code", "Original code$^\\dagger$"), ("Position-force (2ch)", "Position--force"), ("Proposed", "\\textbf{Proposed}")]
out.append("\n\\begin{table}[t]\n\\centering\n\\caption{Torque mimicking in simulation: known forces act on the slave gripper while the "
           "operator holds the master still. Gain: least-squares ratio of felt force to $k_{of}F_{env}$ (1 = exact scaled reproduction).}")
out.append("\\label{tab:sim_mimic}\n\\begin{tabular}{lccccc}\n\\hline")
out.append("\\textbf{Controller} & RMSE (N) & corr.\\ $x$ & corr.\\ $z$ & gain $x$ & gain $z$ \\\\\n\\hline")
for key, lbl in sel:
    r = rows[key]
    out.append(f"{lbl} & {r[0]} & {r[1]} & {r[2]} & {r[3]} & {r[4]} \\\\")
out.append("\\hline\n\\end{tabular}\n\\end{table}")
import re
text = re.sub(r"(?<![\w{}$])-(?=\d)", "$-$", "\n".join(out) + "\n")   # typographic minus in tables
open(os.path.join(HERE, "sim_tables.tex"), "w").write(text)
print(text)
